/**
 * Til kodi bo'yicha til obyektini topish helperi (BCP-47 yoki alias orqali)
 */
export const findLanguageByCode = (langCode) => {
  if (!langCode) return null;
  const clean = langCode.trim().toLowerCase();
  return WORLD_LANGUAGES.find(l => 
    l.code.toLowerCase() === clean ||
    (l.aliases && l.aliases.some(a => a.toLowerCase() === clean)) ||
    clean.startsWith(l.code.toLowerCase().split('-')[0])
  ) || null;
};

/**
 * Foydalanuvchi davlatiga mos standart tilni taklif qilish
 */
export const getSuggestedLanguageForCountry = (countryCode) => {
  if (!countryCode) return null;
  const upper = countryCode.toUpperCase();
  const matched = WORLD_LANGUAGES.find(l => l.countryCodes && l.countryCodes.includes(upper));
  return matched || null;
};
